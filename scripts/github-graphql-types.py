#!/usr/bin/env python3
"""Generate derive-schema types from GitHub's SDL; --check refuses stale output.

Only Python's standard library and rustfmt are needed. The generated crate has no
application dependencies: object values hold an Arc to a per-type resolver trait.
"""
import argparse
from collections import Counter
from dataclasses import dataclass, field
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec/github/schema.docs.graphql"
OUT = ROOT / "crates/codeyard-github-graphql/src"
HEADER = "// @generated by scripts/github-graphql-types.py from spec/github/schema.docs.graphql.\n// Do not edit; rerun the script.\n"
TOKEN = re.compile(r'\s+|\#[^\n]*|,|"""(?:\\"""|[\s\S])*?"""|"(?:\\.|[^"\\])*"|[_A-Za-z][_0-9A-Za-z]*|-?(?:0|[1-9][0-9]*)(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?|[!$():=@\[\]{|}&]')


def rust(value):
    return json.dumps(value, ensure_ascii=False).replace('\\b', '\\u{8}').replace('\\f', '\\u{c}')


def block_string(value):
    lines = value[3:-3].replace('\\"""', '"""').replace('\r\n', '\n').replace('\r', '\n').split('\n')
    indent = min((len(line) - len(line.lstrip(' \t')) for line in lines[1:] if line.strip()), default=0)
    lines = lines[:1] + [line[indent:] for line in lines[1:]]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return '\n'.join(lines)


class EnumValue(str):
    pass


@dataclass(frozen=True)
class Type:
    base: object
    required: bool = False


@dataclass
class Field:
    name: str
    description: object = None
    ty: object = None
    args: list = field(default_factory=list)
    directives: dict = field(default_factory=dict)
    default: object = None
    has_default: bool = False


@dataclass
class Definition:
    kind: str
    name: str
    description: object
    fields: list = field(default_factory=list)
    members: list = field(default_factory=list)
    implements: list = field(default_factory=list)
    directives: dict = field(default_factory=dict)


class Parser:
    def __init__(self, text):
        self.tokens = []
        end = 0
        for match in TOKEN.finditer(text):
            if match.start() != end:
                raise ValueError(f"Unexpected SDL at {end}: {text[end:end+50]!r}")
            token = match.group()
            end = match.end()
            if not token.isspace() and not token.startswith('#') and token != ',':
                self.tokens.append(token)
        if text[end:].strip():
            raise ValueError(f"Unexpected SDL at {end}")
        self.tokens.append(None)
        self.pos = 0
        self.directive_definitions = []

    def peek(self):
        return self.tokens[self.pos]

    def take(self, expected=None):
        token = self.peek()
        if expected is not None and expected != token:
            raise ValueError(f"Expected {expected!r}, got {token!r} near token {self.pos}")
        self.pos += 1
        return token

    def accept(self, token):
        if self.peek() == token:
            self.take()
            return True
        return False

    def description(self):
        token = self.peek()
        if token and token.startswith('"'):
            return self.value()
        return None

    def value(self):
        token = self.take()
        if token.startswith('"""'):
            return block_string(token)
        if token.startswith('"'):
            return json.loads(token)
        if token == '[':
            values = []
            while not self.accept(']'):
                values.append(self.value())
            return values
        if token == '{':
            values = {}
            while not self.accept('}'):
                name = self.take()
                self.take(':')
                values[name] = self.value()
            return values
        if token in ('true', 'false', 'null'):
            return json.loads(token)
        if re.match(r'-?[0-9]', token):
            return json.loads(token)
        return EnumValue(token)

    def ty(self):
        if self.accept('['):
            base = self.ty()
            self.take(']')
        else:
            base = self.take()
        return Type(base, self.accept('!'))

    def directives(self):
        directives = {}
        while self.accept('@'):
            name = self.take()
            args = {}
            if self.accept('('):
                while not self.accept(')'):
                    key = self.take()
                    self.take(':')
                    args[key] = self.value()
            directives[name] = args
        return directives

    def fields(self, closing):
        fields = []
        while not self.accept(closing):
            description = self.description()
            value = Field(self.take(), description)
            if self.accept('('):
                value.args = self.fields(')')
            self.take(':')
            value.ty = self.ty()
            if self.accept('='):
                value.default = self.value()
                value.has_default = True
            value.directives = self.directives()
            fields.append(value)
        return fields

    def parse(self):
        definitions = {}
        while self.peek():
            description = self.description()
            kind = self.take()
            if kind == 'directive':
                self.take('@')
                directive = Definition('directive', self.take(), description)
                if self.accept('('):
                    directive.fields = self.fields(')')
                if self.accept('repeatable'):
                    directive.directives['repeatable'] = {}
                self.take('on')
                self.accept('|')
                directive.members.append(self.take())
                while self.accept('|'):
                    directive.members.append(self.take())
                self.directive_definitions.append(directive)
                continue
            if kind not in ('type', 'interface', 'union', 'enum', 'input', 'scalar'):
                raise ValueError(f"Unsupported SDL definition: {kind}")
            value = Definition(kind, self.take(), description)
            if self.accept('implements'):
                self.accept('&')
                value.implements.append(self.take())
                while self.accept('&'):
                    value.implements.append(self.take())
            value.directives = self.directives()
            if kind == 'union':
                self.take('=')
                self.accept('|')
                value.members.append(self.take())
                while self.accept('|'):
                    value.members.append(self.take())
            elif kind == 'enum':
                self.take('{')
                while not self.accept('}'):
                    desc = self.description()
                    item = Field(self.take(), desc)
                    item.directives = self.directives()
                    value.fields.append(item)
            elif kind != 'scalar':
                self.take('{')
                value.fields = self.fields('}')
            if value.name in definitions:
                raise ValueError(f"Duplicate type: {value.name}")
            definitions[value.name] = value
        return definitions


def snake(value):
    value = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', value)
    value = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', value).lower()
    if value.startswith('from_'):
        value = 'field_' + value
    return 'r#' + value if value in {'type', 'ref', 'match', 'self', 'move', 'as', 'in', 'where', 'loop', 'super', 'crate', 'enum', 'use', 'mod', 'pub', 'fn', 'async', 'await', 'return', 'default', 'const', 'static', 'dyn', 'impl', 'trait', 'unsafe', 'extern', 'box', 'do', 'try', 'union', 'for', 'if', 'else', 'let', 'true', 'false', 'break', 'continue', 'yield'} else value


def enum_variant(name):
    value = ''.join(part[:1].upper() + part[1:].lower() for part in name.split('_'))
    return 'SelfValue' if value == 'Self' else value


def docs(description):
    return f"#[doc = {rust(description)}]\n" if description is not None else ''


def deprecation(directives):
    if 'deprecated' not in directives:
        return []
    reason = directives['deprecated'].get('reason', 'No longer supported')
    return ['deprecation = ' + rust(reason)] if reason is not None else ['deprecation']


def value_expr(value):
    if value is None:
        return 'async_graphql::Value::Null'
    if isinstance(value, EnumValue):
        return f'async_graphql::Value::Enum(async_graphql::Name::new({rust(value)}))'
    if isinstance(value, str):
        return f'async_graphql::Value::String({rust(value)}.into())'
    if isinstance(value, bool):
        return f'async_graphql::Value::Boolean({str(value).lower()})'
    if isinstance(value, (int, float)):
        return f'async_graphql::Value::from({value})'
    if isinstance(value, list):
        return 'async_graphql::Value::List(vec![' + ', '.join(map(value_expr, value)) + '])'
    if isinstance(value, dict):
        return 'async_graphql::Value::Object([' + ', '.join(f'(async_graphql::Name::new({rust(k)}), {value_expr(v)})' for k, v in value.items()) + '].into_iter().collect())'
    raise ValueError(value)


class Generator:
    def __init__(self, definitions, directives=()):
        self.defs = definitions
        self.directive_defs = directives
        self.adapters = {}
        for interface in self.kind('interface'):
            members = [obj for obj in self.kind('type') if interface.name in obj.implements]
            if not members:
                raise ValueError(f"Empty interface: {interface.name}")
            for field in interface.fields:
                signatures = [(f.ty, [(a.name, a.ty) for a in f.args]) for obj in members for f in obj.fields if f.name == field.name]
                if len(signatures) != len(members):
                    raise ValueError(f"Missing interface field: {interface.name}.{field.name}")
                self.adapters[interface.name, field.name] = any(sig != (field.ty, [(a.name, a.ty) for a in field.args]) for sig in signatures)

    def kind(self, kind):
        return [d for d in self.defs.values() if d.kind == kind]

    def ty(self, ty, input=False):
        if isinstance(ty.base, Type):
            base = f'Vec<{self.ty(ty.base, input)}>'
        else:
            base = {'String': '::std::string::String', 'Int': 'i32', 'Float': 'f64', 'Boolean': 'bool', 'ID': 'async_graphql::ID'}.get(ty.base, ty.base)
            if input and ty.base in self.defs and self.defs[ty.base].kind == 'input':
                base = f'crate::Input<{base}>'
        return base if ty.required else f'Option<{base}>'

    def attrs(self, field, interface=False):
        attrs = [f'name = {rust(field.name)}'] + deprecation(field.directives)
        if field.description is not None:
            attrs.append(f'desc = {rust(field.description)}')
        if interface:
            attrs.append(f'ty = {rust(self.ty(field.ty, True))}')
        if field.has_default:
            attrs.append('default_with = ' + rust('crate::default_value(' + value_expr(field.default) + ')'))
        return ', '.join(attrs)

    def enums(self):
        out = []
        for definition in self.kind('enum'):
            variants = [enum_variant(f.name) for f in definition.fields]
            if len(variants) != len(set(variants)):
                raise ValueError(f"Enum variants collide: {definition.name}")
            out.append(docs(definition.description) + '#[derive(async_graphql::Enum, Clone, Copy, Debug, Eq, PartialEq)]\n' + f'#[graphql(name = {rust(definition.name)})]\npub enum {definition.name} {{\n')
            for item in definition.fields:
                attrs = ', '.join([f'name = {rust(item.name)}'] + deprecation(item.directives))
                out.append(docs(item.description) + f'#[graphql({attrs})]\n{enum_variant(item.name)},\n')
            out.append('}\n')
        return ''.join(out)

    def inputs(self):
        out = ['use super::*;\n']
        for definition in self.kind('input'):
            out.append(docs(definition.description) + '#[derive(async_graphql::InputObject, Clone, Debug)]\n' + f'#[graphql(name = {rust(definition.name)})]\npub struct {definition.name} {{\n')
            for item in definition.fields:
                # InputObject uses doc attributes, not the argument-only desc option.
                attrs = [f'name = {rust(item.name)}'] + deprecation(item.directives)
                if item.has_default:
                    attrs.append('default_with = ' + rust('crate::default_value(' + value_expr(item.default) + ')'))
                out.append(docs(item.description) + f'#[graphql({", ".join(attrs)})]\npub {snake(item.name)}: {self.ty(item.ty, True)},\n')
            out.append('}\n')
        return ''.join(out)

    def scalars(self):
        out = []
        for definition in self.kind('scalar'):
            # GitHub's scalars are strings, BigInt included, except CustomPropertyValue, which is a
            # string or a list of strings. Refusing other kinds in parse rejects bad input before any resolver of the same
            # request runs, as GitHub does.
            if definition.name == 'CustomPropertyValue':
                checks = 'fn parse(value: async_graphql::Value) -> async_graphql::InputValueResult<Self> { Ok(Self(value)) }\nfn is_valid(_value: &async_graphql::Value) -> bool { true }\n'
            elif definition.name == 'Date':
                checks = ('fn parse(value: async_graphql::Value) -> async_graphql::InputValueResult<Self> {\n'
                          'if <Self as async_graphql::ScalarType>::is_valid(&value) { Ok(Self(value)) } else { Err(async_graphql::InputValueError::custom("expected a date")) }\n}\n'
                          'fn is_valid(value: &async_graphql::Value) -> bool { crate::is_date(value) }\n')
            else:
                checks = ('fn parse(value: async_graphql::Value) -> async_graphql::InputValueResult<Self> {\n'
                          'if <Self as async_graphql::ScalarType>::is_valid(&value) { Ok(Self(value)) } else { Err(async_graphql::InputValueError::custom("expected a string")) }\n}\n'
                          'fn is_valid(value: &async_graphql::Value) -> bool { matches!(value, async_graphql::Value::String(_)) }\n')
            out.append('#[derive(Clone, Debug)]\n' + f'pub struct {definition.name}(pub async_graphql::Value);\n' + docs(definition.description) + '#[async_graphql::Scalar(name = ' + rust(definition.name) + ')]\nimpl async_graphql::ScalarType for ' + definition.name + ' {\n' + checks + 'fn to_value(&self) -> async_graphql::Value { self.0.clone() }\n}\n')
        return ''.join(out)

    def convert(self, value, source, target):
        if source == target:
            return value
        if not source.required and target.required:
            raise ValueError('Invalid interface covariance')
        if not target.required:
            if source.required:
                return 'Some(' + self.convert(value, source, Type(target.base, True)) + ')'
            return value + '.map(|value| ' + self.convert('value', Type(source.base, True), Type(target.base, True)) + ')'
        if isinstance(source.base, Type) and isinstance(target.base, Type):
            return value + '.into_iter().map(|value| ' + self.convert('value', source.base, target.base) + ').collect()'
        return value + '.into()'

    def adapter_name(self, interface, field):
        return 'interface_' + snake(interface).removeprefix('r#') + '_' + snake(field).removeprefix('r#')

    def objects(self):
        out = ['use super::*;\n']
        for definition in self.kind('type'):
            out.append(f'#[derive(Clone)]\npub struct {definition.name}(::std::sync::Arc<dyn {definition.name}Resolver>);\nimpl {definition.name} {{\npub fn new(resolver: impl {definition.name}Resolver + \'static) -> Self {{ Self(::std::sync::Arc::new(resolver)) }}\n}}\n')
            out.append(docs(definition.description) + f'#[async_graphql::Object(name = {rust(definition.name)})]\nimpl {definition.name} {{\n')
            for item in definition.fields:
                out.append(docs(item.description) + f'#[graphql({", ".join([f"name = {rust(item.name)}"] + deprecation(item.directives))})]\n')
                params = ', '.join(f'#[graphql({self.attrs(a)})] {snake(a.name)}: {self.ty(a.ty, True)}' for a in item.args)
                args = ', '.join(snake(a.name) for a in item.args)
                out.append(f'pub async fn {snake(item.name)}(&self, ctx: &async_graphql::Context<\'_>{", " if params else ""}{params}) -> async_graphql::Result<{self.ty(item.ty)}> {{\nself.0.{snake(item.name)}(ctx{", " if args else ""}{args}).await\n}}\n')
            for interface_name in definition.implements:
                interface = self.defs[interface_name]
                own = {f.name: f for f in definition.fields}
                for item in interface.fields:
                    if not self.adapters[interface_name, item.name]:
                        continue
                    original = own[item.name]
                    params = ', '.join(f'{snake(a.name)}: {self.ty(a.ty, True)}' for a in item.args)
                    available = {a.name for a in item.args}
                    args = []
                    for arg in original.args:
                        if arg.name in available:
                            args.append(snake(arg.name))
                        elif arg.has_default:
                            args.append('crate::default_value(' + value_expr(arg.default) + ')')
                        elif not arg.ty.required:
                            args.append('None')
                        else:
                            raise ValueError(f'Extra required argument on {definition.name}.{item.name}')
                    converted = self.convert('value', original.ty, item.ty)
                    conversion = '' if original.ty == item.ty else '.map(Some)' if converted == 'Some(value)' else f'.map(|value| {converted})'
                    out.append(f'#[graphql(skip)]\npub async fn {self.adapter_name(interface_name, item.name)}(&self, ctx: &async_graphql::Context<\'_>{", " if params else ""}{params}) -> async_graphql::Result<{self.ty(item.ty)}> {{\nself.{snake(item.name)}(ctx{", " if args else ""}{", ".join(args)}).await{conversion}\n}}\n')
            out.append('}\n')
        return ''.join(out)

    def resolvers(self):
        out = ['use super::*;\n']
        for definition in self.kind('type'):
            out.append(f'pub trait {definition.name}Resolver: Send + Sync {{\n')
            for item in definition.fields:
                params = ', '.join(f'_{snake(a.name).removeprefix("r#")}: {self.ty(a.ty, True)}' for a in item.args)
                out.append(f'fn {snake(item.name)}<\'a>(&\'a self, _ctx: &\'a async_graphql::Context<\'_>{", " if params else ""}{params}) -> crate::FieldFuture<\'a, {self.ty(item.ty)}> {{\ncrate::unsupported({rust(definition.name)}, {rust(item.name)})\n}}\n')
            out.append('}\n')
        return ''.join(out)

    def abstracts(self):
        out = ['use super::*;\n']
        for definition in self.kind('interface') + self.kind('union'):
            attrs = [f'name = {rust(definition.name)}']
            if definition.kind == 'interface':
                for item in definition.fields:
                    field_attrs = [f'name = {rust(item.name)}', f'ty = {rust(self.ty(item.ty))}', 'method = ' + rust(self.adapter_name(definition.name, item.name) if self.adapters[definition.name, item.name] else snake(item.name).removeprefix('r#'))] + deprecation(item.directives)
                    if item.description is not None:
                        field_attrs.append(f'desc = {rust(item.description)}')
                    field_attrs += [f'arg({self.attrs(a, True)})' for a in item.args]
                    attrs.append('field(' + ', '.join(field_attrs) + ')')
                members = [obj.name for obj in self.kind('type') if definition.name in obj.implements]
            else:
                members = definition.members
            out.append(docs(definition.description) + f'#[derive(async_graphql::{"Interface" if definition.kind == "interface" else "Union"}, Clone)]\n#[graphql({", ".join(attrs)})]\npub enum {definition.name} {{\n')
            out.extend(f'{name}({name}),\n' for name in members)
            out.append('}\n')
        return ''.join(out)

    def directives(self):
        def option(value):
            return 'None' if value is None else f'Some({rust(value)}.into())'
        def gql_type(ty):
            base = '[' + gql_type(ty.base) + ']' if isinstance(ty.base, Type) else ty.base
            return base + ('!' if ty.required else '')
        out = ['use async_graphql::registry::{MetaDirective, MetaInputValue, Deprecation, __DirectiveLocation};\nuse crate::schema_directive::SchemaDirective;\npub(crate) fn definitions() -> Vec<SchemaDirective> { vec![\n']
        for directive in self.directive_defs:
            out.append(f'SchemaDirective(MetaDirective {{ name: {rust(directive.name)}.into(), description: {option(directive.description)}, locations: vec![' + ', '.join('__DirectiveLocation::' + location for location in directive.members) + '], args: [\n')
            for arg in directive.fields:
                if arg.has_default or arg.directives:
                    raise ValueError('Directive argument metadata needs default/deprecation support')
                out.append(f'({rust(arg.name)}.into(), MetaInputValue {{ name: {rust(arg.name)}.into(), description: {option(arg.description)}, ty: {rust(gql_type(arg.ty))}.into(), deprecation: Deprecation::NoDeprecated, default_value: None, visible: None, inaccessible: false, tags: vec![], is_secret: false, directive_invocations: vec![] }}),\n')
            out.append('].into_iter().collect(), is_repeatable: ' + str('repeatable' in directive.directives).lower() + ', visible: None, composable: None }),\n')
        out.append('] }\n')
        return ''.join(out)

    def schema(self):
        # Bound unoptimized stack frames instead of keeping 1,824 moved builders in one function.
        definitions = list(self.defs.values())
        chunks = [definitions[i:i+64] for i in range(0, len(definitions), 64)]
        out = ['use super::*;\ntype Builder = async_graphql::SchemaBuilder<Query, Mutation, async_graphql::EmptySubscription>;\n', 'pub(crate) fn build(query: Query, mutation: Mutation) -> Builder {\nlet builder = async_graphql::Schema::build(query, mutation, async_graphql::EmptySubscription).limit_depth(20).limit_complexity(1000).limit_recursive_depth(64);\n']
        for i in range(len(chunks)):
            out.append(f'let builder = register_{i}(builder);\n' if i < len(chunks)-1 else f'register_{i}(builder)\n}}\n')
        for i, chunk in enumerate(chunks):
            out.append(f'fn register_{i}(builder: Builder) -> Builder {{\n')
            for j, definition in enumerate(chunk):
                method = 'register_input_type' if definition.kind == 'input' else 'register_output_type'
                call = f'builder.{method}::<{definition.name}>()'
                out.append(f'let builder = {call};\n' if j < len(chunk)-1 else call + '\n}\n')
        seen = set()
        def visit(name):
            if name in seen or name not in self.defs:
                return
            seen.add(name)
            definition = self.defs[name]
            for item in definition.fields:
                for ty in ([item.ty] if item.ty else []) + [a.ty for a in item.args]:
                    while isinstance(ty.base, Type):
                        ty = ty.base
                    visit(ty.base)
            for member in definition.members + definition.implements:
                visit(member)
            if definition.kind == 'interface':
                for obj in self.kind('type'):
                    if name in obj.implements:
                        visit(obj.name)
        visit('Query')
        visit('Mutation')
        orphans = [d for d in self.defs.values() if d.name not in seen]
        if any(d.kind != 'union' for d in orphans):
            raise ValueError('Introspection support is needed for new orphan type kinds')
        out.append('pub(crate) const ORPHAN_UNIONS: &[&str] = &[' + ', '.join(rust(d.name) for d in orphans) + '];\n')
        return ''.join(out)

    def render(self):
        return {name + '.rs': HEADER + ('#![allow(clippy::too_many_arguments)]\n' if name in ('objects', 'resolvers') else '') + ('// Interface attributes repeat ty/desc keys in distinct field and argument groups.\n#![allow(clippy::duplicated_attributes)]\n' if name == 'abstracts' else '') + getattr(self, name)() for name in ('objects', 'resolvers', 'inputs', 'enums', 'scalars', 'abstracts', 'schema', 'directives')}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    document = Parser(SPEC.read_text())
    definitions = document.parse()
    generated = Generator(definitions, document.directive_definitions).render()
    stale = []
    for name, text in generated.items():
        formatted = subprocess.run(['rustfmt', '--edition', '2021'], input=text, text=True, capture_output=True, check=True).stdout
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != formatted:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(formatted)
    if stale:
        sys.exit('Out of date; rerun scripts/github-graphql-types.py: ' + ', '.join(stale))
    counts = Counter(d.kind for d in definitions.values())
    print(', '.join(f'{count} {kind}' for kind, count in sorted(counts.items())))


if __name__ == '__main__':
    main()
